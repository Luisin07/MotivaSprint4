-- ===== BLOCO 3: sequences (INCREMENT BY 1 casa com allocationSize = 1 nas entities) =====
CREATE SEQUENCE SEQ_MOT_EQUIPE      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MOT_TRECHO      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MOT_INTERVENCAO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MOT_RELATORIO   START WITH 1 INCREMENT BY 1 NOCACHE;

-- ===== BLOCO 4: equipe_manutencao (DEFAULT NEXTVAL mantém o INSERT manual do script-dados funcionando) =====
CREATE TABLE T_MOT_EQUIPE (
    ID_EQUIPE          NUMBER        DEFAULT SEQ_MOT_EQUIPE.NEXTVAL PRIMARY KEY,
    NM_EQUIPE          VARCHAR2(80)  NOT NULL,
    NM_RESPONSAVEL     VARCHAR2(80)  NOT NULL,
    QT_MEMBROS         NUMBER(3)     NOT NULL CHECK (QT_MEMBROS > 0),
    DS_ESPECIALIDADE   VARCHAR2(60)  NOT NULL,
    ST_ATIVA           CHAR(1)       DEFAULT 'S' NOT NULL CHECK (ST_ATIVA IN ('S','N'))
);

-- ===== BLOCO 5: trecho_rodovia =====
CREATE TABLE T_MOT_TRECHO (
    ID_TRECHO           NUMBER        DEFAULT SEQ_MOT_TRECHO.NEXTVAL PRIMARY KEY,
    CD_RODOVIA          VARCHAR2(15)  NOT NULL,
    KM_INICIAL          NUMBER(7,2)   NOT NULL,
    KM_FINAL            NUMBER(7,2)   NOT NULL,
    NR_INDICE_DESGASTE  NUMBER(5,2)   NOT NULL CHECK (NR_INDICE_DESGASTE BETWEEN 0 AND 100),
    QT_ACIDENTES_ANO    NUMBER(5)     DEFAULT 0 NOT NULL,
    VL_FLUXO_DIARIO     NUMBER(9)     NOT NULL,
    CONSTRAINT CK_MOT_TRECHO_KM CHECK (KM_FINAL > KM_INICIAL)
);

-- ===== BLOCO 6: intervencao_operacional (liga trecho + equipe) =====
CREATE TABLE T_MOT_INTERVENCAO (
    ID_INTERVENCAO  NUMBER        DEFAULT SEQ_MOT_INTERVENCAO.NEXTVAL PRIMARY KEY,
    ID_TRECHO       NUMBER        NOT NULL,
    ID_EQUIPE       NUMBER        NOT NULL,
    DS_TIPO         VARCHAR2(60)  NOT NULL,
    DT_INICIO       DATE          NOT NULL,
    DT_FIM          DATE,
    DS_STATUS       VARCHAR2(20)  NOT NULL CHECK (DS_STATUS IN ('PLANEJADA','EM_ANDAMENTO','CONCLUIDA','CANCELADA')),
    CONSTRAINT FK_MOT_INTERV_TRECHO FOREIGN KEY (ID_TRECHO) REFERENCES T_MOT_TRECHO (ID_TRECHO),
    CONSTRAINT FK_MOT_INTERV_EQUIPE FOREIGN KEY (ID_EQUIPE) REFERENCES T_MOT_EQUIPE (ID_EQUIPE)
);

-- ===== BLOCO 7: relatorio_prioridade (histórico gerado pelo POST /api/relatorios) =====
CREATE TABLE T_MOT_RELATORIO (
    ID_RELATORIO  NUMBER         DEFAULT SEQ_MOT_RELATORIO.NEXTVAL PRIMARY KEY,
    DT_GERACAO    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    QT_URGENTE    NUMBER(5)      NOT NULL,
    QT_CRITICO    NUMBER(5)      NOT NULL,
    QT_ATENCAO    NUMBER(5)      NOT NULL,
    QT_NORMAL     NUMBER(5)      NOT NULL,
    DS_RESUMO     VARCHAR2(1000)
);
